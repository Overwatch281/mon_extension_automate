"""Regular (right-linear) grammars, and their link with automata (#55)."""

from automata_extensions.grammar.cfg import ContextFreeGrammar


class RegularGrammar(ContextFreeGrammar):
    """
    A right-linear grammar, which generates a regular language.

    Every production is ``A -> w`` or ``A -> w B``, where w is a (possibly
    empty) sequence of terminals and B is a nonterminal. The constructor
    takes the same arguments as `ContextFreeGrammar` and checks this form.

    Raises
    ------
    ValueError
        If a production is not right-linear (in addition to the errors of
        `ContextFreeGrammar`).
    """

    def __init__(self, productions, start, nonterminals=None, terminals=None):
        super().__init__(productions, start, nonterminals, terminals)
        if not self.is_right_linear():
            raise ValueError(
                "the grammar is not right-linear: every production must be "
                "A -> w or A -> w B, with w made of terminals"
            )

    def to_nfa(self):
        """
        Convert the grammar to an NFA (#55).

        Each nonterminal becomes a state and the start symbol becomes the
        initial state. A new state is the only final state. A production
        ``A -> a B`` becomes a transition from A to B on a, and ``A -> a``
        a transition from A to the final state. When the terminal part of
        a production has several symbols, intermediate states are added
        (named ``A_1``, ``A_2``, ...). A production ``A -> B`` or
        ``A -> epsilon`` becomes an epsilon transition to B or to the
        final state. The grammar is never modified.

        Returns
        -------
        ExtendedNFA
            An NFA recognizing the language generated by the grammar.

        Complexity
        ----------
        O(size of the grammar)

        References
        ----------
        Hopcroft, Motwani & Ullman, *Introduction to Automata Theory,
        Languages, and Computation*.
        """
        # Imported here to avoid a circular import between the packages.
        from automata_extensions.fa.nfa import ExtendedNFA

        used = set(self.nonterminals) | set(self.terminals)

        def fresh(base):
            """Return `base`, or `base_1`, `base_2`... if the name is taken."""
            name, counter = base, 0
            while name in used:
                counter += 1
                name = f"{base}_{counter}"
            used.add(name)
            return name

        final_state = fresh("F")
        transitions = {nonterminal: {} for nonterminal in self.nonterminals}
        transitions[final_state] = {}

        def link(source, symbol, target):
            transitions.setdefault(target, {})
            transitions[source].setdefault(symbol, set()).add(target)

        for rule in self.productions:
            if rule.right and rule.right[-1] in self.nonterminals:
                body, target = rule.right[:-1], rule.right[-1]
            else:
                body, target = rule.right, final_state

            current = rule.left
            for symbol in body[:-1]:
                following = fresh(rule.left)
                link(current, symbol, following)
                current = following
            if body:
                link(current, body[-1], target)
            else:
                link(current, '', target)

        return ExtendedNFA(
            states=set(transitions),
            input_symbols=self.terminals,
            transitions=transitions,
            initial_state=self.start,
            final_states={final_state},
        )

    @classmethod
    def from_automaton(cls, automaton):
        """
        Build the right-linear grammar of a DFA or an NFA (#55).

        Each state becomes a nonterminal and the initial state becomes the
        start symbol. A transition from p to q on a gives the production
        ``p -> a q`` (an epsilon transition gives ``p -> q``), and a final
        state p gives ``p -> epsilon``. The nonterminals are named after
        the states; if these names are ambiguous (two states with the same
        name, or a name equal to a symbol), they are named Q0, Q1, ...
        instead.

        Parameters
        ----------
        automaton : Automaton
            An extended DFA or NFA.

        Returns
        -------
        RegularGrammar
            A grammar generating the language of the automaton.

        Complexity
        ----------
        O(|Q| + |E|)

        References
        ----------
        Hopcroft, Motwani & Ullman, *Introduction to Automata Theory,
        Languages, and Computation*.
        """
        from automata_extensions.fa.mixins.visualisation import _state_label

        states = sorted(automaton.states, key=_state_label)
        symbols = set(automaton.input_symbols)
        labels = [_state_label(state) for state in states]

        if len(set(labels)) == len(labels) and all(labels) and not set(labels) & symbols:
            names = dict(zip(states, labels))
        else:
            prefix = "Q"
            while any(f"{prefix}{index}" in symbols for index in range(len(states))):
                prefix += "_"
            names = {state: f"{prefix}{index}" for index, state in enumerate(states)}

        productions = []
        for state in states:
            row = automaton.transitions.get(state, {})
            for symbol in sorted(row):
                targets = sorted(automaton._destination_states(row[symbol]), key=_state_label)
                for target in targets:
                    right = (names[target],) if symbol == '' else (symbol, names[target])
                    productions.append((names[state], right))
            if state in automaton.final_states:
                productions.append((names[state], ()))

        return cls(
            productions,
            start=names[automaton.initial_state],
            nonterminals=set(names.values()),
            terminals=symbols,
        )